//! `options-doc`: the options reference (`docs/options.md`) from the option declarations (docs/design/05-options-and-report.md): every
//! `#[derive(Options)]` struct is a section, every field a row. `--check` compares instead of writing, for CI.
use anyhow::{bail, Context, Result};
use clap::Args as ClapArgs;
use flyhigh_engine::options::groups;
use std::path::PathBuf;

#[derive(ClapArgs)]
pub struct Args {
    /// The file to write or to check (default: docs/options.md of this repository)
    pub path: Option<PathBuf>,
    /// Compare the file with the generated text and exit 1 when it is stale, instead of writing it
    #[arg(long)]
    pub check: bool,
}

const HEAD: &str = "# Options

Generated by `flyhigh-dev options-doc` from the option declarations in the engine (`#[derive(Options)]`, docs/design/05-options-and-report.md):
edit the doc comments there, not this file; CI fails when it is stale.

Every option has a default: a host that passes nothing gets the configuration below. Change an option only for the
reason in its row. The same options exist in every API: Rust takes the structs named in each section, C the
`Fh*Options` structs (start from `fh_*_options_default()`; the field in the last column), JavaScript the options objects
of the classes ([api-js.md](api-js.md)).
";

pub fn render() -> String {
    let mut s = String::from(HEAD);
    for g in groups() {
        s.push_str(&format!("\n## {} options\n\n{}\n\n", g.name, g.doc));
        s.push_str("| Option | Default | Values | What it does, when to change it | C |\n|---|---|---|---|---|\n");
        for o in g.options {
            s.push_str(&format!("| `{}` | {} | {} | {} | `{}` |\n", o.name, o.default, o.values, o.doc, o.c));
        }
    }
    s
}

pub fn run(a: Args) -> Result<()> {
    let path = a.path.unwrap_or_else(|| super::repo_root().join("docs").join("options.md"));
    let text = render();
    if a.check {
        let current = std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
        if current.replace("\r\n", "\n") != text {
            bail!("{} is stale: run `flyhigh-dev options-doc`", path.display());
        }
        println!("{} is current", path.display());
        return Ok(());
    }
    std::fs::write(&path, &text).with_context(|| format!("write {}", path.display()))?;
    println!("wrote {} ({} options)", path.display(), groups().iter().map(|g| g.options.len()).sum::<usize>());
    Ok(())
}
